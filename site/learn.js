// ------------------------------------------------------------------ 開關與點擊
export function explainOn() { return !!settings.explain; }
export function setExplain(on) {
  settings.explain = !!on;
  saveSettings();
  document.body.classList.toggle('explain', settings.explain);
}
export function openTerm(key, el) {
  const T = TERMS[key];
  if (!T) return;
  const row = exRow(el);
  let ex = '';
  try { ex = T.ex ? T.ex(row) : ''; } catch { ex = ''; }
  openModal(`<div class="form term">
      <div class="term-k">冷眼小辭典</div>
      <h2 class="m-title">${esc(T.t)}</h2>
      ${T.b.map((p) => `<p class="term-p">${esc(p)}</p>`).join('')}
      ${ex ? `<div class="term-ex"><span>現在的例子</span><p>${esc(ex)}</p></div>` : ''}
      <div class="m-actions"><button type="button" class="btn ghost" data-close>知道了</button></div>
    </div>`, { label: T.t });
}
/** 看懂模式打開時，點到有 data-term 的字，就攔下來顯示解釋（不會順便打開那一列） */
export function installExplain() {
  document.body.classList.toggle('explain', explainOn());
  document.addEventListener('click', (e) => {
    if (!explainOn()) return;
    const t = e.target.closest('[data-term]');
    if (!t || t.closest('.modal')) return;
    e.preventDefault();
    e.stopPropagation();
    openTerm(t.dataset.term, t);
  }, true);
}
export function glossaryHTML() {
  return `<div class="gloss">${Object.entries(TERMS).map(([k, v]) => `<button class="gl-row" data-gl="${k}">${esc(v.t)}</button>`).join('')}</div>`;
}
export function bindGlossary(root) {
  $$('[data-gl]', root).forEach((b) => b.addEventListener('click', () => openTerm(b.dataset.gl, b)));
}
