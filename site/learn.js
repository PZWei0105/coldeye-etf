const r2 = (x) => (isNum(x) ? x.toFixed(2) : '—');
const pc = (x, d = 1) => (isNum(x) ? `${x > 0 ? '+' : ''}${(x * 100).toFixed(d)}%` : '—');
/** 舉例用的 ETF：點的那一列 → 單檔頁 → 關注第一檔 → 0050 */
function exRow(el) {
  const code = (el && (el.closest('[data-code]') || {}).dataset?.code) || (S.openCode && S.openCode !== '__prefs' ? S.openCode : null)
    || (settings.watch || [])[0] || '0050';
  return S.rows.get(code) || S.rows.get('0050') || null;
}

